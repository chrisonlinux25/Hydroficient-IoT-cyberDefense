import pandas as pd
import json

"""**Question 1 — Load the JSON**
upload the file/csv/json into the left sidebar --> Files
"""

with open("sample.json","r")as file:
  data=json.load(file)

"""***Question 2 — Get order IDs and total amounts***"""

for customer in data:
  for order in customer["orders"]:
    print(order["order_id"],order["total"])

"""***Question 3 — Normalize the JSON into a Flat DataFrame***"""

df = pd.json_normalize(data,record_path=["orders", "items"], meta=[
        "customer_id",
        ["orders", "order_id"],
        ["orders", "total"]
    ]
)
#Note from christine khayat, additional code to rename and make the table more clear.
df = df.rename(columns={
    "orders.order_id": "order_id",
    "orders.total": "total"
})

df = df[["customer_id", "order_id", "product", "quantity", "total"]]

df

"""***Question 4 — Save the Processed DataFrame as a JSON File***"""

df.to_json("processed_orders.json", orient="records", indent=4)