"""---
## Section 2: Baseline Isolation Forest Model

Train a baseline Isolation Forest with default-ish parameters and see how it performs.

### How Isolation Forest Works

Imagine you have a room full of people standing in a group. If you wanted to isolate one specific person, you'd draw random lines through the room to separate them. For someone standing in the middle of the crowd, you'd need many lines (splits) to isolate them. For someone standing far from the group, just one or two lines would do it.

Isolation Forest works the same way with data points. It builds many random decision trees that split the data. Points that are easy to isolate (need fewer splits) get lower "anomaly scores" — they're the outliers. Points deep in the crowd (need many splits) get higher scores — they're normal.

**Why this works for IoT security:** Normal sensor readings cluster together in predictable ranges. A pressure reading of 60 PSI sits in the middle of the crowd. A reading of 85 PSI stands far away and gets isolated quickly — the model flags it as anomalous.
"""

# =============================================================================
# Train Baseline Isolation Forest
# =============================================================================

# contamination = expected fraction of anomalies in the data
# We know we injected ~5% anomalies (50 out of 1050)
model = IsolationForest(contamination=0.1, random_state=42)

# Train the model
start_time = time.time()
model.fit(X)
train_time = time.time() - start_time

# Get predictions: 1 = normal, -1 = anomaly
