"""### Understanding the Results: Precision, Recall, and F1

These three metrics tell you different things about how well the model performed:

- **Precision** answers: "When the model raised an alarm, how often was it right?" A precision of 0.90 means 90% of flagged readings were actual anomalies, and 10% were false alarms. High precision = few false alarms.

- **Recall** answers: "Of all the actual anomalies, how many did the model catch?" A recall of 0.80 means the model caught 80% of anomalies but missed 20%. High recall = few missed anomalies.

- **F1 Score** is the balance between precision and recall. It's high only when both precision and recall are high. For IoT security, you generally want high recall (don't miss real anomalies) even if it means slightly lower precision (a few extra false alarms are acceptable).

**Concrete example:** If there were 50 real anomalies in your data and the model flagged 55 readings total, with 45 of those being actual anomalies:
- Precision = 45/55 = 0.82 (82% of alarms were real)
- Recall = 45/50 = 0.90 (caught 90% of anomalies)
- The 10 false alarms and 5 missed anomalies are the trade-off
"""

# =============================================================================
# Evaluate Baseline Results
# =============================================================================

def evaluate_model(true_labels, pred_labels, model_name="Model"):
    """Calculate and print precision, recall, F1 for anomaly detection."""
    # Convert to binary: anomaly=1, normal=0 (for sklearn metrics)
    true_binary = (true_labels == -1).astype(int)
    pred_binary = (pred_labels == -1).astype(int)

    tp = ((pred_binary == 1) & (true_binary == 1)).sum()
    fp = ((pred_binary == 1) & (true_binary == 0)).sum()
    fn = ((pred_binary == 0) & (true_binary == 1)).sum()
    tn = ((pred_binary == 0) & (true_binary == 0)).sum()

    precision = precision_score(true_binary, pred_binary, zero_division=0)
    recall = recall_score(true_binary, pred_binary, zero_division=0)
    f1 = f1_score(true_binary, pred_binary, zero_division=0)

    print(f"\n{'='*50}")
    print(f"  {model_name} Results")
    print(f"{'='*50}")
    print(f"  True Positives  (correctly flagged):   {tp}")
    print(f"  False Positives (normal flagged):      {fp}")
    print(f"  False Negatives (anomalies missed):    {fn}")
    print(f"  True Negatives  (correctly passed):    {tn}")
    print(f"  ---")
    print(f"  Precision: {precision:.3f}")
    print(f"  Recall:    {recall:.3f}")
    print(f"  F1 Score:  {f1:.3f}")
    print(f"{'='*50}")

    return {"precision": precision, "recall": recall, "f1": f1,
            "tp": tp, "fp": fp, "fn": fn, "tn": tn}

